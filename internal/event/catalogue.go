/*
The catalogue: everything that could happen, and everywhere it could
legitimately happen.

technical.md §4 settles what this is. **Daily conflicts and job situations are
authored pathways, selected deterministically** — not generated by a model
(§7) — and §4 calls that "a real content cost". So this is content in the repo
(technical.md §5.2), loaded and validated at boot, and the module below it holds
no opinion about what any of it means.

The one thing worth reading twice is [Placement]. §4 says placement conditions
and the world's trigger zones "are the same objects", and this is where that
becomes true rather than aspirational: an author writes zones out of
internal/city's closed vocabulary, the whole set of legitimate (place, zone)
pairs is resolved here at boot, and an event whose placement resolves to nowhere
is a failed build. Nothing downstream can place an event where its rules
disallow, because the release path has nothing but this list to place it from.
*/

// Kind is the family an event belongs to.
//
// It exists because §4 makes declining a *signal* — "a player routing around
// every interpersonal encounter is telling the release policy something worth
// acting on" — and a signal has to be counted by something. Four families,
// closed and validated at boot, because a release policy (#22) that had to
// handle an unknown one would be a policy with a default in it.
type Kind string

const (
	// Interpersonal is another person, wanting something or offering it.
	Interpersonal Kind = "interpersonal"
	// Work is the job and the people it comes with (§3.4).
	Work Kind = "work"
	// Money is a moment that is about what it costs.
	Money Kind = "money"
	// Opportunity is a door standing open, with nobody asking anything.
	Opportunity Kind = "opportunity"
)

// Kinds is every family, in the order a screen should group them.
var Kinds = []Kind{Interpersonal, Work, Money, Opportunity}

// KindOf reads a family off a content file or the wire, refusing anything else.
func KindOf(s string) (Kind, bool) {
	for _, k := range Kinds {
		if Kind(s) == k {
			return k, true
		}
	}
	return "", false
}

/*
Surface is which of §4's two delivery surfaces an event arrives on.

§4's table is emphatic that they are distinct systems rather than one
abstraction: "the sandbox feel depends on not everything arriving as a push."
[InWorld] is found by walking (§3.12's encounter surface) and [InQueue] may also
be surfaced when the player opens the game.

What it is *not* is an exemption from placement. Both kinds are placed at the
player's own place against the same authored rules, so a pushed event is still
never placed absurdly — it is only pushed about.
*/
type Surface string

const (
	// InWorld is found by walking into it.
	InWorld Surface = "world"
	// InQueue may also be surfaced when the player looks.
	InQueue Surface = "queue"
)

// Surfaces is every surface. Two, and §4 argues at length that it should not
// become one.
var Surfaces = []Surface{InWorld, InQueue}

// SurfaceOf reads a surface off a content file, refusing anything else.
func SurfaceOf(s string) (Surface, bool) {
	for _, f := range Surfaces {
		if Surface(s) == f {
			return f, true
		}
	}
	return "", false
}

// Day is how a patience or a cooldown authored in days is held.
const Day = 24 * time.Hour

/*
Spot is one legitimate placement: a place, and the named zone inside it.

The pair rather than either half, because "at the counter" is not a place and
"the corner shop" is not somewhere to stand. It is what the release path hands
to the client, and it is what a painting draws a marker in (§10.3).
*/
type Spot struct {
	Place string
	Zone  string
}

/*
Placement is every spot an event may legitimately be placed in.

Resolved once at boot from what the author wrote — some combination of places,
layers and districts, narrowed by zones — into the concrete pairs. Two
consequences, both of them the ticket rather than an optimisation:

  - **An event is never placed somewhere its rules disallow.** There is no
    predicate evaluated at release time that could be wrong; there is a list,
    and a place is in it or it is not.
  - **An event that can never appear anywhere is a failed build.** A zone
    misspelt, or named for a place that has no such spot, means the resolved set
    is empty and the loader panics — rather than the event quietly never
    happening, which is the failure this whole arrangement exists to make
    impossible.
*/
type Placement struct {
	// spots is place key → the zones allowed there, in the city's own priority
	// order (most specific first), so `Where` needs no tie-break of its own.
	spots map[string][]string
	// places is the same keys in the city's authored order, for tests and for
	// anything that wants to read the rules back.
	places []string
}

// Where is the zone an event would be placed in at a given place, and whether
// it may be placed there at all.
//
// The city orders a place's zones most specific first, so the answer to "the
// stoop or just the street" is the stoop without anybody authoring a priority.
func (p Placement) Where(place string) (string, bool) {
	zones := p.spots[place]
	if len(zones) == 0 {
		return "", false
	}
	return zones[0], true
}

// Allows reports whether a particular spot is one of the legitimate ones.
func (p Placement) Allows(place, zone string) bool {
	for _, z := range p.spots[place] {
		if z == zone {
			return true
		}
	}
	return false
}

// Places is every place this event may appear in, in the city's order.
func (p Placement) Places() []string {
	out := make([]string, len(p.places))
	copy(out, p.places)
	return out
}

// Spots is every legitimate placement, place by place.
func (p Placement) Spots() []Spot {
	out := make([]Spot, 0, len(p.places))
	for _, place := range p.places {
		for _, zone := range p.spots[place] {
			out = append(out, Spot{Place: place, Zone: zone})
		}
	}
	return out
}

/*
Needs is what has to be true of the *player* for a moment to make sense.

Separate from [Placement] because the two are checked for different reasons:
placement asks whether the spot makes sense and is fixed for the life of the
content, while this asks whether the moment does and can be true on Monday and
false on Tuesday. §4 requires it to be re-checked at release — "a backlogged
event is re-checked against current state before being surfaced, and silently
dropped or requeued if its preconditions no longer hold" — which is only
meaningful for conditions that move.

Deliberately small. Everything here is a bound on money, because money is the
one thing about a player this module can read without reaching into somebody
else's tables (§3.1, and see [Purse]). A precondition on the body or on a factor
wants an interface of its own and a ticket that has a use for it.
*/
type Needs struct {
	// AtLeast is a floor on what the player is holding, and Least is whether
	// there is one. A pointer would say the same thing and would make the
	// zero value of a Needs a thing to be careful with.
	Least   bool
	AtLeast simulation.Money
	Most    bool
	AtMost  simulation.Money
}

// Any reports whether anything is required at all.
func (n Needs) Any() bool { return n.Least || n.Most }

// Met reports whether the preconditions hold in the circumstances given.
func (n Needs) Met(c Circumstances) bool {
	if n.Least && c.Money < n.AtLeast {
		return false
	}
	if n.Most && c.Money > n.AtMost {
		return false
	}
	return true
}

// Circumstances is the player as a precondition is allowed to see them: where
// they are standing, and what they are holding.
type Circumstances struct {
	Place string
	Money simulation.Money
}

/*
Event is one authored thing that could happen.

It carries no state and no player. A row in the backlog is an instance of one of
these for one account; this is the thing itself, shared by everybody and edited
by an author rather than by the game.
*/
type Event struct {
	Key  string
	Name string
	Kind Kind
	// Surface is how it is released, never whether it is placed (see [Surface]).
	Surface Surface

	// Line is the moment, in the second person. Accept and Decline are the two
	// things a player may do about it, in their own words — and Decline is
	// worded as walking away rather than as refusing forever, because §3.9 says
	// declining does not consume it.
	Line    string
	Accept  string
	Decline string
	// After is what accepting came to, for an event that finishes on the spot.
	// Empty exactly when Awaits is set.
	After string
	// Awaits is whether accepting opens something this module does not finish —
	// a challenge (#23), a job situation (#28), a conflict (#30). The record
	// stays pending until that module calls Resolve.
	Awaits bool

	Where Placement
	Needs Needs

	// Patience is how long it may sit in the backlog before the world gives up
	// on it and drops it (§4's other half of revalidation).
	Patience time.Duration
	// Again is how long after it is done before it may be generated again.
	// Zero means never again.
	Again time.Duration
	// Then is the successor queued the moment this one is responded to (§4:
	// "events chain"). Empty for most things.
	Then string
	// Chained is whether some other event names this one as its successor.
	// **Derived, not authored** — an event that can only arrive by chaining is
	// a fact about the catalogue rather than a property somebody remembers to
	// set, and the two going out of step would either duplicate a chain or
	// strand it.
	Chained bool
	// Weight is which of two placeable events is preferred. Ties break on how
	// little the player has seen the event and then on the authored order, so
	// nothing here is ever decided by chance (§7).
	Weight int
}

/* ── the catalogue, loaded once ────────────────────────────────────────── */

// events is every authored event, in a stable order: weight first, then by key.
//
// Loaded and validated at init, and a panic if it is wrong — the same decision
// internal/city and internal/playbook take, for the same reason. Content that
// cannot be loaded should stop a deploy, not produce a world with a hole in it.
var events = mustLoad()

func mustLoad() []Event {
	loaded, err := parse(content.FS)
	if err != nil {
		panic("event: " + err.Error())
	}
	return loaded
}

// All is every authored event, in the catalogue's order.
func All() []Event {
	out := make([]Event, len(events))
	copy(out, events)
	return out
}

// Known finds an event by key. The false is a real answer: an event withdrawn
// from content leaves rows behind it in every player's backlog, and the release
// path drops them rather than failing.
func Known(key string) (Event, bool) {
	for _, e := range events {
		if e.Key == key {
			return e, true
		}
	}
	return Event{}, false
}

/* ── reading the files ─────────────────────────────────────────────────── */

// eventFile is one YAML file, exactly.
//
// Strict decoding (see [decode]) means a field that is not here is a failed
// build rather than a line of content silently ignored — so this struct is the
// authoring contract, and adding a field to the content means adding it here
// first.
type eventFile struct {
	Key     string `yaml:"key"`
	Name    string `yaml:"name"`
	Kind    string `yaml:"kind"`
	Surface string `yaml:"surface"`

	Line    string `yaml:"line"`
	Accept  string `yaml:"accept"`
	Decline string `yaml:"decline"`
	After   string `yaml:"after"`
	Awaits  bool   `yaml:"awaits"`

	Where struct {
		Places    []string `yaml:"places"`
		Layers    []string `yaml:"layers"`
		Districts []string `yaml:"districts"`
		Zones     []string `yaml:"zones"`
	} `yaml:"where"`

	Needs struct {
		AtLeast *int64 `yaml:"money-at-least"`
		AtMost  *int64 `yaml:"money-at-most"`
	} `yaml:"needs"`

	Patience int    `yaml:"patience"`
	Again    int    `yaml:"again"`
	Then     string `yaml:"then"`
	Weight   int    `yaml:"weight"`
}

/*
parse reads a whole directory of event files and validates them together.

Together rather than one at a time, because three of the rules are about the
catalogue as a whole: a key used twice, a successor that names nothing, and a
chain that eventually points back at itself. The last of those is the one worth
having a check for — a cycle would be a player answering the same two events
forever, and it is invisible in either file on its own.

The parameter is an fs.FS so a test can drive it over an in-memory tree rather
than over what happens to ship.
*/
func parse(fsys fs.FS) ([]Event, error) {
	entries, err := fs.ReadDir(fsys, "events")
	if err != nil {
		return nil, fmt.Errorf("read the events: %w", err)
	}

	var (
		out   []Event
		files = map[string]eventFile{}
	)
	for _, entry := range entries {
		if entry.IsDir() || path.Ext(entry.Name()) != ".yaml" {
			continue
		}
		raw, err := fs.ReadFile(fsys, path.Join("events", entry.Name()))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", entry.Name(), err)
		}

		var file eventFile
		if err := decode(raw, &file); err != nil {
			return nil, fmt.Errorf("read %s: %w", entry.Name(), err)
		}

		e, err := build(file)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", entry.Name(), err)
		}
		if _, clash := files[e.Key]; clash {
			return nil, fmt.Errorf("%s: two events called %q", entry.Name(), e.Key)
		}
		files[e.Key] = file
		out = append(out, e)
	}

	if len(out) == 0 {
		return nil, fmt.Errorf("there are no events at all")
	}

	// Successors, and what they imply. An event named as somebody's `then` is
	// chained, which is derived here rather than authored — see Event.Chained.
	chained := map[string]string{}
	for _, e := range out {
		if e.Then == "" {
			continue
		}
		if e.Then == e.Key {
			return nil, fmt.Errorf("%s is its own successor", e.Key)
		}
		if _, ok := find(out, e.Then); !ok {
			return nil, fmt.Errorf("%s is followed by %q, which is not an event", e.Key, e.Then)
		}
		if first, taken := chained[e.Then]; taken {
			return nil, fmt.Errorf("%s and %s are both followed by %s", first, e.Key, e.Then)
		}
		chained[e.Then] = e.Key
	}
	for i := range out {
		if _, ok := chained[out[i].Key]; !ok {
			continue
		}
		out[i].Chained = true
		if out[i].Again != 0 {
			// A cooldown on generation says nothing about an event that is
			// never generated, and an author who wrote one meant something
			// else — probably that the chain should repeat, which is the
			// parent's `again` and not this one's.
			return nil, fmt.Errorf("%s is only ever chained and names a cooldown", out[i].Key)
		}
	}
	if err := acyclic(out); err != nil {
		return nil, err
	}

	// Stable order: heaviest first, then by key. Every list this package makes
	// comes out of this one, so two identical worlds release the same event.
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Weight != out[j].Weight {
			return out[i].Weight > out[j].Weight
		}
		return out[i].Key < out[j].Key
	})
	return out, nil
}

// build turns one file into an event, refusing everything that is not one.
func build(file eventFile) (Event, error) {
	out := Event{
		Key:      strings.TrimSpace(file.Key),
		Name:     strings.TrimSpace(file.Name),
		Line:     strings.TrimSpace(file.Line),
		Accept:   strings.TrimSpace(file.Accept),
		Decline:  strings.TrimSpace(file.Decline),
		After:    strings.TrimSpace(file.After),
		Awaits:   file.Awaits,
		Then:     strings.TrimSpace(file.Then),
		Patience: time.Duration(file.Patience) * Day,
		Again:    time.Duration(file.Again) * Day,
		Weight:   file.Weight,
	}

	if out.Key == "" {
		return Event{}, fmt.Errorf("an event needs a key")
	}
	for _, missing := range []struct {
		field string
		value string
	}{
		{"name", out.Name},
		{"line", out.Line},
		{"accept", out.Accept},
		{"decline", out.Decline},
	} {
		if missing.value == "" {
			return Event{}, fmt.Errorf("%s has no %s", out.Key, missing.field)
		}
	}

	// The one place where two fields have to agree: an event that finishes on
	// the spot says what it came to, and one that opens something else cannot
	// possibly know yet.
	switch {
	case out.Awaits && out.After != "":
		return Event{}, fmt.Errorf("%s waits on something else and already says how it went", out.Key)
	case !out.Awaits && out.After == "":
		return Event{}, fmt.Errorf("%s finishes on the spot and does not say what it came to", out.Key)
	}

	kind, ok := KindOf(file.Kind)
	if !ok {
		return Event{}, fmt.Errorf("%s is a %q, which is not a kind of event", out.Key, file.Kind)
	}
	out.Kind = kind

	surface, ok := SurfaceOf(file.Surface)
	if !ok {
		return Event{}, fmt.Errorf("%s arrives on %q, which is not a surface", out.Key, file.Surface)
	}
	out.Surface = surface

	if out.Patience <= 0 {
		return Event{}, fmt.Errorf("%s never gives up waiting", out.Key)
	}
	if out.Again < 0 {
		return Event{}, fmt.Errorf("%s comes round again in the past", out.Key)
	}
	if out.Weight <= 0 {
		return Event{}, fmt.Errorf("%s is worth nothing", out.Key)
	}

	if file.Needs.AtLeast != nil {
		out.Needs.Least, out.Needs.AtLeast = true, simulation.Money(*file.Needs.AtLeast)
	}
	if file.Needs.AtMost != nil {
		out.Needs.Most, out.Needs.AtMost = true, simulation.Money(*file.Needs.AtMost)
	}
	if out.Needs.Least && out.Needs.Most && out.Needs.AtLeast > out.Needs.AtMost {
		return Event{}, fmt.Errorf("%s needs more money than it allows", out.Key)
	}

	where, err := placement(file)
	if err != nil {
		return Event{}, fmt.Errorf("%s: %w", out.Key, err)
	}
	out.Where = where

	return out, nil
}

/*
placement resolves what an author wrote into the concrete spots.

The three ways of naming places are additive and all of them are optional
individually — `places` for the specific, `layers` for "any interior", and
`districts` for "anywhere in the east side, inside or out". What is not optional
is the result: an event with no legitimate spot is refused here, which is the
whole reason placement is resolved at boot instead of evaluated at release.
*/
func placement(file eventFile) (Placement, error) {
	if len(file.Where.Zones) == 0 {
		return Placement{}, fmt.Errorf("names no zones to be placed in")
	}
	zones := map[string]bool{}
	for _, z := range file.Where.Zones {
		if !city.Zone(z) {
			return Placement{}, fmt.Errorf("names the zone %q, which is not a kind of spot", z)
		}
		zones[z] = true
	}

	wanted := map[string]bool{}
	for _, key := range file.Where.Places {
		if !city.Known(key) {
			return Placement{}, fmt.Errorf("names the place %q, which is nowhere", key)
		}
		wanted[key] = true
	}
	for _, layer := range file.Where.Layers {
		found := false
		for _, p := range city.Places() {
			if string(p.Layer) == layer {
				wanted[p.Key], found = true, true
			}
		}
		if !found {
			return Placement{}, fmt.Errorf("names the layer %q, which is not one", layer)
		}
	}
	for _, district := range file.Where.Districts {
		outer, ok := city.Lookup(district)
		if !ok || outer.Layer != city.District {
			return Placement{}, fmt.Errorf("names the district %q, which is not one", district)
		}
		wanted[district] = true
		for _, p := range city.Places() {
			if p.In == district {
				wanted[p.Key] = true
			}
		}
	}
	if len(wanted) == 0 {
		return Placement{}, fmt.Errorf("names nowhere to happen")
	}

	out := Placement{spots: map[string][]string{}}
	// The city's own order, place by place and zone by zone, so priority is
	// the city's opinion about which spot is the more specific rather than the
	// order somebody happened to type the zones in.
	for _, p := range city.Places() {
		if !wanted[p.Key] {
			continue
		}
		var allowed []string
		for _, z := range city.ZonesIn(p.Key) {
			if zones[z] {
				allowed = append(allowed, z)
			}
		}
		if len(allowed) == 0 {
			continue
		}
		out.spots[p.Key] = allowed
		out.places = append(out.places, p.Key)
	}
	if len(out.places) == 0 {
		return Placement{}, fmt.Errorf("has no spot anywhere: no place it names has any of its zones")
	}
	return out, nil
}

// acyclic refuses a chain that eventually points back at itself.
//
// Each event has at most one successor and at most one thing chaining to it, so
// the graph is a set of paths — and a cycle is the one shape that is not a
// path. It would be a player answering the same run of events forever, which
// nobody would author on purpose and which no single file shows.
func acyclic(all []Event) error {
	for _, start := range all {
		at, seen := start, map[string]bool{start.Key: true}
		for at.Then != "" {
			next, ok := find(all, at.Then)
			if !ok {
				break
			}
			if seen[next.Key] {
				return fmt.Errorf("%s is followed, eventually, by itself", start.Key)
			}
			seen[next.Key] = true
			at = next
		}
	}
	return nil
}

func find(all []Event, key string) (Event, bool) {
	for _, e := range all {
		if e.Key == key {
			return e, true
		}
	}
	return Event{}, false
}

/*
decode reads one YAML document strictly.

KnownFields(true) is the whole point: a misspelt field is a failed build rather
than a silently ignored line of content. It is the same helper internal/playbook
uses, and it is duplicated rather than shared because §3.1 puts the parsing of a
kind of content in the module that owns it — the two would otherwise grow a
shared "content utilities" package that knows what both of them mean.
*/
func decode(raw []byte, into any) error {
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	dec.KnownFields(true)
	if err := dec.Decode(into); err != nil {
		return err
	}
	return nil
}
