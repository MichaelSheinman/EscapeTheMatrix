/*
The catalogue: everything a delegated role can put to somebody who is not there.

technical.md §4 settles what this is, in one sentence that names this ticket:
**"daily conflicts and job situations are authored pathways per environment,
selected deterministically from relationship state"** — not generated by a model
(§7). So it is content in the repo (§5.2), loaded and validated at boot, and the
module below it holds no opinion about what any of it means.

# A situation is a moment plus its consequences, and nothing else

Three parts, and the split is the whole design of §3.14:

  - **The moment.** What happened, in words, and the questions it puts to the
    playbook — written in the *matcher's* vocabulary, because a situation the
    matcher cannot read is a situation the character cannot handle.
  - **The facts.** What was true of it, stated as the vocabulary states things.
    This is what makes a rule's condition mean something: "they are paying me
    above $60" is only a test if the moment says what it pays.
  - **The answers.** One per posture the moment could be met with, each with
    what the character did, what came of it, and the authored hidden deltas
    (§3.5) that follow.

An answer is keyed by a [playbook.Stance] rather than by an action term, and
that is deliberate. The vocabulary has four ways to say yes and the world has
one consequence for saying it: what a situation has to have an answer for is
what the rule *amounted to*, not which word the player reached for. It is also
what makes a situation and a rule set independent — a term added to a question
later needs no edit here.

# Nothing here says which answer is right

§3.2's "nothing is labelled", applied to the one place it would be easiest to
break. An `outcome` is `good`, `mixed` or `poor` *for this moment*, and the
player is never shown it as a verdict on their rule — they are shown what
happened, in `came`, and the counts add up over a week into §3.15's pattern.
Nothing anywhere ranks the postures, and the same posture is authored good in
one situation and poor in another, which is §3.15's whole thesis in miniature.
*/

/*
Answer is one posture a moment can be met with, and everything that follows from
meeting it that way.

`Did` is written as the thing the character did rather than as an instruction,
because it is read in two places that have to agree: the log, after the rules
decided, and the live decision, before the player does. A line that read as a
button in one and as a report in the other would be two pieces of writing
pretending to be one.
*/
type Answer struct {
	Stance playbook.Stance
	// Did is what the character does, in the second person.
	Did string
	// Came is what it came to. The consequence §3.14's loop step 2 is about, and
	// the only account of how it went the player ever gets.
	Came string
	// Outcome is how the world took it: good, mixed or poor. Never [Pending] —
	// an authored answer is a settled one by construction.
	Outcome playbook.Outcome
	// Moves is §3.5's authored hidden deltas, in the pure core's own order. Only
	// the three factors that are granted rather than read: a situation that
	// moved Health or Money would be a job editing a body or a balance behind
	// the two modules that own them.
	Moves []simulation.Grant
}

/*
Authored is one situation, whole.

It carries the [playbook.Situation] it puts rather than the raw facts, because
the facts are only meaningful once they have been resolved against the
vocabulary — and resolving them at boot is what makes a misspelt term a failed
build rather than a rule that quietly never matched.
*/
type Authored struct {
	Key string
	// Tier is the rung of §3.14's ladder that produces this. Always at or above
	// [simulation.Delegated]: the passive tiers "pay without being played", and a
	// situation authored for one of them would be a job that is not the job the
	// design describes.
	Tier simulation.Tier
	Name string
	// Line is the moment itself, in the second person.
	Line string

	moment  playbook.Situation
	answers []Answer
}

// Moment is what the matcher is asked about.
func (a Authored) Moment() playbook.Situation { return a.moment }

// Puts is the questions this moment raises, in authored order.
func (a Authored) Puts() []string { return a.moment.Puts() }

// Answers is every posture this moment has been written an answer for, in the
// stance vocabulary's own order.
func (a Authored) Answers() []Answer {
	out := make([]Answer, len(a.answers))
	copy(out, a.answers)
	return out
}

// Answer finds the one written for a posture.
func (a Authored) Answer(s playbook.Stance) (Answer, bool) {
	for _, ans := range a.answers {
		if ans.Stance == s {
			return ans, true
		}
	}
	return Answer{}, false
}

/*
catalogue is the one parsed copy, built at process start.

A package-level value for the same reason internal/playbook's vocabulary is: it
is authored content with no state in it, identical in every process, and a
second copy could only ever be a second opinion.
*/
var catalogue []Authored

/*
init parses and validates the shipped content, and panics if it cannot.

technical.md §5.2: "production validates at startup so a malformed challenge
fails in CI, not at 2am." A panic here is that, and it is why `parse` takes an
fs.FS rather than reading the embedded files itself — the failure paths are
worth testing, and a test cannot catch an init that already ran.
*/
func init() {
	all, err := parse(content.FS)
	if err != nil {
		panic("situation: " + err.Error())
	}
	catalogue = all
}

// All is every authored situation, in the order they are loaded (by key).
func All() []Authored {
	out := make([]Authored, len(catalogue))
	copy(out, catalogue)
	return out
}

// Known finds one by key.
func Known(key string) (Authored, bool) {
	for _, a := range catalogue {
		if a.Key == key {
			return a, true
		}
	}
	return Authored{}, false
}

/*
For is every situation a rung produces, in catalogue order.

The pool a day's moment is drawn from. A tier with an empty pool produces
nothing at all, which is the correct behaviour for a rung nobody has authored
work for yet and is checked at boot for every rung the ladder actually has above
[simulation.Delegated].
*/
func For(tier simulation.Tier) []Authored {
	out := []Authored{}
	for _, a := range catalogue {
		if a.Tier == tier {
			out = append(out, a)
		}
	}
	return out
}

/* ── reading the files ─────────────────────────────────────────────────── */

const situationsPath = "situations"

// The YAML shape. Separate from the types above on purpose: what an author
// writes and what the rest of the program reads are two decisions, and a
// situation that carried its file's field names would make renaming one a
// migration.
type situationFile struct {
	Key   string   `yaml:"key"`
	Tier  int      `yaml:"tier"`
	Name  string   `yaml:"name"`
	Line  string   `yaml:"line"`
	Puts  []string `yaml:"puts"`
	Facts []struct {
		Term string `yaml:"term"`
		// So states a term that takes no number. Reading states one that does,
		// in its value list's unit. Exactly one of them is written, and which
		// one is decided by the vocabulary rather than by this file.
		So      *bool  `yaml:"so"`
		Reading *int64 `yaml:"reading"`
	} `yaml:"facts"`
	Answers []struct {
		Stance  string             `yaml:"stance"`
		Did     string             `yaml:"did"`
		Came    string             `yaml:"came"`
		Outcome string             `yaml:"outcome"`
		Moves   map[string]float64 `yaml:"moves"`
	} `yaml:"answers"`
}

/*
parse reads the catalogue out of a content filesystem and checks every rule the
rest of this package then gets to assume.

It is strict twice over, in the same two ways internal/playbook's loader is.
Unknown YAML fields are refused, so a misspelt `puts:` is a failed build rather
than a moment that puts nothing; and every cross-reference — a question, a term,
a value, a posture, a factor — is resolved here rather than at the moment a
player happens to reach it.

The one check worth reading twice is the last: **every posture the questions can
produce has an answer.** A moment whose rules could reach a posture nobody wrote
a consequence for is a moment the character can handle and the world cannot
respond to, and it would surface as a rule that silently did nothing — which is
the exact failure §3.14 says has to be legible.
*/
func parse(files fs.FS) ([]Authored, error) {
	entries, err := fs.ReadDir(files, situationsPath)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", situationsPath, err)
	}

	var out []Authored
	seen := map[string]bool{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}
		name := path.Join(situationsPath, entry.Name())

		var file situationFile
		if err := decode(files, name, &file); err != nil {
			return nil, err
		}
		a, err := situation(file)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		// The key is the filename, so that a situation recorded against a
		// player has one name in the table, in the log and on disk.
		if stem := strings.TrimSuffix(entry.Name(), ".yaml"); a.Key != stem {
			return nil, fmt.Errorf("%s: is called %q", name, a.Key)
		}
		if seen[a.Key] {
			return nil, fmt.Errorf("%s: two situations called %q", name, a.Key)
		}
		seen[a.Key] = true
		out = append(out, a)
	}

	if len(out) == 0 {
		return nil, fmt.Errorf("%s holds no situations", situationsPath)
	}
	// By key, so the pool a day is drawn from is in the same order in every
	// process. A directory walk is already sorted on every filesystem this runs
	// on; saying so is what makes the determinism a decision (§7).
	sort.Slice(out, func(i, j int) bool { return out[i].Key < out[j].Key })

	// Every rung the ladder has above the line §3.14 draws produces work. A
	// delegated role with an empty pool is a job that pays for nothing, which
	// is the state #27 deliberately left and this ticket closes.
	for _, rung := range simulation.Rungs() {
		if rung.Tier < simulation.Delegated {
			continue
		}
		empty := true
		for _, a := range out {
			if a.Tier == rung.Tier {
				empty = false
			}
		}
		if empty {
			return nil, fmt.Errorf("%s: tier %d is active and has no situations", situationsPath, rung.Tier)
		}
	}
	return out, nil
}

func situation(file situationFile) (Authored, error) {
	if file.Key == "" {
		return Authored{}, fmt.Errorf("a situation has no key")
	}
	if file.Name == "" || file.Line == "" {
		return Authored{}, fmt.Errorf("%q needs a name and a line", file.Key)
	}

	tier := simulation.Tier(file.Tier)
	if _, on := simulation.Rungs().At(tier); !on {
		return Authored{}, fmt.Errorf("%q is tier %d, which is not a rung of the ladder", file.Key, file.Tier)
	}
	// The passive rungs "pay without being played" (§3.14). A situation
	// authored for one of them would arrive on a job whose whole property is
	// that nothing arrives on it.
	if tier < simulation.Delegated {
		return Authored{}, fmt.Errorf("%q is tier %d, which is passive; a delegated role is tier %d or above",
			file.Key, file.Tier, simulation.Delegated)
	}

	if len(file.Puts) == 0 {
		return Authored{}, fmt.Errorf("%q puts no question, so nothing in a playbook could answer it", file.Key)
	}
	vocab := playbook.Vocab()
	asked := map[string]playbook.Question{}
	for _, key := range file.Puts {
		q, ok := vocab.Question(key)
		if !ok {
			return Authored{}, fmt.Errorf("%q puts %q, which the world does not ask", file.Key, key)
		}
		if _, twice := asked[key]; twice {
			return Authored{}, fmt.Errorf("%q puts %q twice", file.Key, key)
		}
		asked[key] = q
	}

	moment := playbook.Arises(file.Key, file.Puts...)
	for _, f := range file.Facts {
		if f.Term == "" {
			return Authored{}, fmt.Errorf("%q states a fact with no term", file.Key)
		}
		term, ok := vocab.Term(f.Term)
		if !ok {
			return Authored{}, fmt.Errorf("%q states %q, which is not a term", file.Key, f.Term)
		}
		// A fact about a question nobody is putting is a fact nothing can test.
		// It would read as an authored subtlety and behave as a typo.
		if _, puts := asked[term.Question]; !puts {
			return Authored{}, fmt.Errorf("%q states %q and does not put %q", file.Key, f.Term, term.Question)
		}
		switch {
		case f.So != nil && f.Reading != nil:
			return Authored{}, fmt.Errorf("%q states %q both ways", file.Key, f.Term)
		case f.Reading != nil:
			moment = moment.Reading(f.Term, *f.Reading)
		case f.So != nil:
			moment = moment.So(f.Term, *f.So)
		default:
			return Authored{}, fmt.Errorf("%q states %q and says nothing about it", file.Key, f.Term)
		}
	}
	// The matcher's own reading of the same question, which catches the one
	// thing the loop above cannot: a term stated as the wrong sort of thing.
	if faults := moment.Faults(); len(faults) > 0 {
		return Authored{}, fmt.Errorf("%q states %s in a way the vocabulary cannot read",
			file.Key, strings.Join(faults, ", "))
	}

	out := Authored{Key: file.Key, Tier: tier, Name: file.Name, Line: strings.TrimSpace(file.Line), moment: moment}

	written := map[playbook.Stance]bool{}
	for _, a := range file.Answers {
		answer, err := reply(file.Key, a.Stance, a.Did, a.Came, a.Outcome, a.Moves)
		if err != nil {
			return Authored{}, err
		}
		if written[answer.Stance] {
			return Authored{}, fmt.Errorf("%q answers %q twice", file.Key, answer.Stance)
		}
		written[answer.Stance] = true
		out.answers = append(out.answers, answer)
	}

	// Every posture the moment's own questions can reach, and no others. Both
	// halves matter: an unanswered posture is a rule the world cannot respond
	// to, and an answer for a posture no rule here could take is writing nobody
	// will ever read.
	reachable := postures(asked, file.Puts)
	for _, s := range reachable {
		if !written[s] {
			return Authored{}, fmt.Errorf("%q can be met with %q and has no answer for it", file.Key, s)
		}
	}
	for _, a := range out.answers {
		if !contains(reachable, a.Stance) {
			return Authored{}, fmt.Errorf("%q answers %q, which none of its questions can reach", file.Key, a.Stance)
		}
	}
	// The stance vocabulary's order rather than the file's, so two situations
	// offer the same postures in the same order however they were written.
	sort.SliceStable(out.answers, func(i, j int) bool {
		return rankStance(out.answers[i].Stance) < rankStance(out.answers[j].Stance)
	})
	return out, nil
}

// reply reads one answer.
func reply(key, stance, did, came, outcome string, moves map[string]float64) (Answer, error) {
	s := playbook.Stance(stance)
	if !contains(playbook.Stances, s) {
		return Answer{}, fmt.Errorf("%q answers with %q, which is not one of %v", key, stance, playbook.Stances)
	}
	if strings.TrimSpace(did) == "" || strings.TrimSpace(came) == "" {
		return Answer{}, fmt.Errorf("%q's %q answer needs both what was done and what came of it", key, stance)
	}

	out := Answer{Stance: s, Did: strings.TrimSpace(did), Came: strings.TrimSpace(came)}
	switch playbook.Outcome(outcome) {
	case playbook.Good, playbook.Mixed, playbook.Poor:
		out.Outcome = playbook.Outcome(outcome)
	default:
		return Answer{}, fmt.Errorf("%q's %q answer came to %q, which is not one of %q, %q, %q",
			key, stance, outcome, playbook.Good, playbook.Mixed, playbook.Poor)
	}

	for _, name := range sorted(moves) {
		which, err := moved(name)
		if err != nil {
			return Answer{}, fmt.Errorf("%q's %q answer %w", key, stance, err)
		}
		out.Moves = append(out.Moves, simulation.Grant{Factor: which, Credit: moves[name]})
	}
	return out, nil
}

// postures is every stance the actions of these questions can amount to, in the
// stance vocabulary's order.
//
// The whole pool rather than the terms a player has unlocked: a situation is
// content and outlives any one player's vocabulary, and a moment that could not
// be answered by somebody who has earned every word is a moment with a hole in
// it whether or not anybody has reached it yet.
func postures(asked map[string]playbook.Question, order []string) []playbook.Stance {
	seen := map[playbook.Stance]bool{}
	for _, key := range order {
		for _, t := range asked[key].Actions() {
			seen[t.Stance] = true
		}
	}
	out := []playbook.Stance{}
	for _, s := range playbook.Stances {
		if seen[s] {
			out = append(out, s)
		}
	}
	return out
}

// sorted is a `moves` block's factor names in the simulation's own order.
//
// The same function internal/challenge's loader has, and for the same reason:
// map iteration in Go is deliberately random, and authored grants that arrived
// in a different order on every boot would be §7's determinism lost to a detail
// of the language rather than to a decision.
func sorted(moves map[string]float64) []string {
	out := make([]string, 0, len(moves))
	for name := range moves {
		out = append(out, name)
	}
	sort.Slice(out, func(i, j int) bool { return rank(out[i]) < rank(out[j]) })
	return out
}

func rank(name string) int {
	for i, f := range simulation.Factors {
		if f.Key() == name {
			return i
		}
	}
	return len(simulation.Factors)
}

func rankStance(s playbook.Stance) int {
	for i, known := range playbook.Stances {
		if known == s {
			return i
		}
	}
	return len(playbook.Stances)
}

/*
moved is the factor a `moves:` line names.

It refuses Health and Money by name rather than by a generic message, because
the thing an author needs told is *which* factors this may move — the three that
are scored from committed choices (§3.5). A job situation that moved a body or a
balance would be this module writing behind internal/health and
internal/character, which own them.
*/
func moved(name string) (simulation.Factor, error) {
	var granted []string
	for _, f := range simulation.Factors {
		if f.Granted() {
			granted = append(granted, f.Key())
		}
	}
	for _, f := range simulation.Factors {
		if f.Key() != name {
			continue
		}
		if !f.Granted() {
			return 0, fmt.Errorf("moves %s, which is read from the world rather than granted (a situation moves %s)",
				name, strings.Join(granted, ", "))
		}
		return f, nil
	}
	return 0, fmt.Errorf("moves %q, which is not a factor (a situation moves %s)",
		name, strings.Join(granted, ", "))
}

func contains[T comparable](list []T, want T) bool {
	for _, x := range list {
		if x == want {
			return true
		}
	}
	return false
}

// decode reads one YAML file strictly: an unknown field is a failed build
// rather than an authored line nobody notices has no effect.
func decode(files fs.FS, name string, into any) error {
	raw, err := fs.ReadFile(files, name)
	if err != nil {
		return fmt.Errorf("read %s: %w", name, err)
	}
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	dec.KnownFields(true)
	if err := dec.Decode(into); err != nil {
		return fmt.Errorf("read %s: %w", name, err)
	}
	return nil
}
